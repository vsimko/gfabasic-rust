#!/usr/bin/env python3
"""Generate the Rust view of the canonical API registry's handler requirements."""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_ROOT = ROOT / "api" / "registry"
OUTPUT = ROOT / "crates" / "gfabasic-runtime" / "src" / "handlers" / "generated.rs"

PROFILES = {
    "language-core": "LanguageCore",
    "amiga": "Amiga",
    "atari-st": "AtariSt",
}
STATUSES = {
    "implemented": "Implemented",
    "partial": "Partial",
    "not-implemented": "NotImplemented",
    "unsafe-disabled": "UnsafeDisabled",
}


class GenerationError(ValueError):
    """The canonical registry cannot be represented by the runtime ABI."""


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def signature_for(declaration: dict, status: str, path: Path) -> str:
    if status not in {"implemented", "partial"}:
        return "Unsupported"

    if declaration.get("kind") != "function":
        raise GenerationError(f"{path}: callable handler {declaration['id']} must be a function")
    signature = declaration.get("signature", {})
    if signature.get("returns") != "arithmetic expression":
        raise GenerationError(f"{path}: unsupported return type for {declaration['id']}")

    syntax = declaration.get("syntax", [])
    if len(syntax) != 1 or syntax[0].get("contexts") != ["expression"]:
        raise GenerationError(f"{path}: handler {declaration['id']} needs one expression syntax")
    arguments = syntax[0].get("arguments", [])
    if len(arguments) not in {1, 2} or any(
        argument.get("type") != "integer expression" or argument.get("required") is not True
        for argument in arguments
    ):
        raise GenerationError(f"{path}: unsupported argument signature for {declaration['id']}")
    return "IntegerToUnsigned" if len(arguments) == 1 else "TwoIntegersToUnsigned"


def generate_source(root: Path = ROOT) -> str:
    registry_root = root / "api" / "registry"
    requirements = []
    seen_ids: set[str] = set()
    seen_handlers: set[str] = set()

    for path in sorted(registry_root.rglob("*.toml")):
        relative = path.relative_to(registry_root)
        namespace = relative.parts[0]
        if namespace not in PROFILES:
            raise GenerationError(f"{path}: unknown registry namespace {namespace!r}")
        try:
            data = tomllib.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
            raise GenerationError(f"{path}: cannot read registry TOML: {exc}") from exc

        for declaration in data.get("declarations", []):
            declaration_id = declaration.get("id", "")
            if not declaration_id or declaration_id in seen_ids:
                raise GenerationError(f"{path}: missing or duplicate declaration ID {declaration_id!r}")
            seen_ids.add(declaration_id)

            implementation = declaration.get("implementation", {})
            raw_status = implementation.get("status")
            if raw_status not in STATUSES:
                raise GenerationError(f"{path}: unsupported implementation status {raw_status!r}")
            status = STATUSES[raw_status]
            handler_id = implementation.get("handler")
            if raw_status in {"implemented", "partial"}:
                if not isinstance(handler_id, str) or not handler_id:
                    raise GenerationError(f"{path}: callable declaration {declaration_id} has no handler ID")
                if handler_id in seen_handlers:
                    raise GenerationError(f"{path}: duplicate handler ID {handler_id!r}")
                seen_handlers.add(handler_id)
            elif handler_id is not None:
                raise GenerationError(f"{path}: non-callable declaration {declaration_id} must not name a handler")

            signature = signature_for(declaration, raw_status, path)
            requirements.append(
                (declaration_id, handler_id, PROFILES[namespace], status, signature)
            )

    requirements.sort(key=lambda item: item[0])
    lines = [
        "//! Generated from api/registry/*.toml by scripts/generate_runtime_handler_requirements.py.",
        "//! Do not edit this file by hand.",
        "",
        "use super::{ApiProfile, HandlerRequirement, HandlerSignature, ImplementationStatus};",
        "",
        "pub const API_HANDLER_REQUIREMENTS: &[HandlerRequirement<'static>] = &[",
    ]
    for declaration_id, handler_id, profile, status, signature in requirements:
        handler = "None" if handler_id is None else f"Some({rust_string(handler_id)})"
        lines.append(
            "    HandlerRequirement { "
            f"id: {rust_string(declaration_id)}, handler_id: {handler}, "
            f"profile: ApiProfile::{profile}, status: ImplementationStatus::{status}, "
            f"signature: HandlerSignature::{signature} "
            "},"
        )
    lines.extend(["];", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()
    try:
        generated = generate_source()
    except GenerationError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"ERROR: {OUTPUT.relative_to(ROOT)} is stale; run this script without --check", file=sys.stderr)
            return 1
        print(f"Runtime handler requirements are up to date ({generated.count('HandlerRequirement {')} declarations).")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
